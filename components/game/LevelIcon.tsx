"use client";
import { useEffect, useRef } from "react";
import { LEVELS, MISS_COLOR } from "@/lib/scoring";
import type { Level } from "@/types";

/* 12x12 pixel icons, one per answer level. '#' is the level colour, 'o' is a white highlight. */
const ICONS: Record<string, string[]> = {
  1: ["....####....", "..########..", "..#......#..", "..#.####.#..", "..#......#..", "..#.####.#..", "..#......#..", "..#.####.#..", "..#......#..", "..#......#..", "..########..", "............"],
  2: ["............", ".##########.", ".#........#.", ".#.######.#.", ".#........#.", ".#.####...#.", ".#........#.", ".##########.", "...##.......", "...#........", "............", "............"],
  3: ["..##....##..", "..##....##..", "...##..##...", "....####....", "...######...", "..########..", "..###oo###..", "..###oo###..", "..########..", "...######...", "....####....", "............"],
  4: [".#..........", ".#######....", ".#########..", ".###########", ".#########..", ".#######....", ".#..........", ".#..........", ".#..........", ".#..........", ".#..........", "###........."],
  5: [".....##.....", ".....##.....", "....####....", "############", ".##########.", "..########..", "...######...", "..########..", "..###..###..", ".###....###.", ".##......##.", "............"],
  6: ["....####....", "...#oooo#...", "..#oo##oo#..", ".#oo#..#oo#.", ".#o#....#o#.", "..#o#..#o#..", "...#o##o#...", "....#oo#....", ".....##.....", "...######...", "..########..", "............"],
  "-1": ["............", ".##......##.", "..##....##..", "...##..##...", "....####....", ".....##.....", "....####....", "...##..##...", "..##....##..", ".##......##.", "............", "............"],
};

export function LevelIcon({ level }: { level: Level | -1 }) {
  const ref = useRef<HTMLCanvasElement>(null);
  useEffect(() => {
    const c = ref.current?.getContext("2d");
    if (!c) return;
    const main = level === -1 ? MISS_COLOR : LEVELS[level].color;
    c.clearRect(0, 0, 12, 12);
    ICONS[String(level)].forEach((row, y) => {
      for (let x = 0; x < 12; x++) {
        if (row[x] === ".") continue;
        c.fillStyle = row[x] === "o" ? "#fff" : main;
        c.fillRect(x, y, 1, 1);
      }
    });
  }, [level]);
  return <canvas ref={ref} id="icon" width={12} height={12} aria-hidden="true" />;
}
